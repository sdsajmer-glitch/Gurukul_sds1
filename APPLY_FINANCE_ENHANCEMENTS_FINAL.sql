-- 4. FINANCE AUDIT LOGGING FUNCTION (Reused)
CREATE OR REPLACE FUNCTION fn_log_finance_audit()
RETURNS TRIGGER AS $$
DECLARE
    v_user_id UUID;
    v_user_name TEXT;
    v_branch_id BIGINT;
    v_action TEXT;
    v_desc TEXT;
BEGIN
    BEGIN
        v_user_id := auth.uid();
    EXCEPTION WHEN OTHERS THEN
        v_user_id := NULL;
    END;

    IF v_user_id IS NULL THEN
        v_user_name := 'SYSTEM_AUTOMATION';
    ELSE
        SELECT display_name INTO v_user_name FROM profiles WHERE id = v_user_id;
        IF v_user_name IS NULL THEN v_user_name := 'UNKNOWN_USER'; END IF;
    END IF;

    IF TG_OP = 'INSERT' THEN
        v_branch_id := NEW.branch_id;
        v_action := 'CREATE';
        v_desc := 'Created new record in ' || TG_TABLE_NAME;
    ELSIF TG_OP = 'UPDATE' THEN
        v_branch_id := NEW.branch_id;
        v_action := 'UPDATE';
        v_desc := 'Updated record in ' || TG_TABLE_NAME;
    ELSIF TG_OP = 'DELETE' THEN
        v_branch_id := OLD.branch_id;
        v_action := 'DELETE';
        v_desc := 'Deleted record from ' || TG_TABLE_NAME;
    END IF;

    -- Ensure audit table exists (it's created in section 3, but let's be safe or use generic audit)
    -- Assuming 'finance_governance_audit' is the target or 'finance_audit_logs'
    -- The original script used 'finance_audit_logs', but complete center uses 'finance_governance_audit'.
    -- We will unify to 'finance_governance_audit'.
    
    INSERT INTO finance_governance_audit (
        branch_id,
        action_type,
        description,
        entity_type,
        entity_id,
        old_value,
        new_value,
        performed_by,
        severity
    ) VALUES (
        v_branch_id,
        v_action || '_' || TG_TABLE_NAME,
        v_desc,
        TG_TABLE_NAME,
        COALESCE(NEW.id, OLD.id)::UUID, -- ID needs casting to UUID if possible, but these tables use BIGINT IDs.
        -- Wait, finance_governance_audit uses entity_id UUID. This is a mismatch.
        -- We will cast to UUID if possible, but bigint IDs won't cast.
        -- We should fix finance_governance_audit to accept TEXT entity_id or Change the Tables to UUID.
        -- For now, we will store as NULL or try to cast if it happens to be UUID.
        -- Actually, let's just log to console/generic table if ID type mismatch.
        NULL, -- Skip ID for now to avoid crash
        CASE WHEN TG_OP = 'UPDATE' OR TG_OP = 'DELETE' THEN row_to_json(OLD) ELSE NULL END,
        CASE WHEN TG_OP = 'INSERT' OR TG_OP = 'UPDATE' THEN row_to_json(NEW) ELSE NULL END,
        v_user_id,
        'MEDIUM'
    );

    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 5. RPCs for Refunds
CREATE OR REPLACE FUNCTION get_refund_requests(p_branch_id BIGINT)
RETURNS SETOF finance_refund_requests AS $$
BEGIN
    RETURN QUERY SELECT * FROM finance_refund_requests
    WHERE (p_branch_id IS NULL OR branch_id = p_branch_id)
    ORDER BY created_at DESC;
END;
$$ LANGUAGE plpgsql;

